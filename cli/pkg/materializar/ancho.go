package materializar

// Ancho son las columnas que ocupa un texto en un terminal: un emoji o un carácter ancho (CJK) ocupa dos, un selector
// de variante (U+FE0F) hace ancho al carácter anterior y una tilde que combina no ocupa nada.
func Ancho(s string) int {
	total, ultima := 0, 0
	for _, r := range s {
		w := anchoRuna(r)
		if w == 0 {
			n := anchoCon(r, ultima)
			total += n - ultima
			ultima = n
			continue
		}
		total += w
		ultima = w
	}
	return total
}

// anchoCon es el ancho del carácter anterior cuando lo sigue r, de ancho cero: el selector de emoji lo deja en dos.
func anchoCon(r rune, anterior int) int {
	if r == 0xFE0F {
		return 2
	}
	return anterior
}

var anchosCero = [][2]rune{{0x0300, 0x036F}, {0x200B, 0x200F}, {0x20D0, 0x20FF}, {0xFE00, 0xFE0F}, {0xE0100, 0xE01EF}}

